"""Designs the filters src/tests/iir_filter_test.cpp runs, with SciPy, and writes them as C++.

IirFilter takes its coefficients as compile-time constants, so the designs are written into
src/tests/iir_filter_test_designs.cpp, which the test includes. That file is tracked: run this
again only to change the designs.

Usage, from the repository's root:
    uv run --project scripts/python scripts/python/design_iir_test_filters.py
"""

from dataclasses import dataclass
from pathlib import Path

import numpy as np
from scipy import signal

# The test stream's rate (see TestStream in iir_filter_test.cpp).
SAMPLING_RATE = 30000.0


@dataclass(frozen=True)
class Design:
    name: str
    family: str  # SciPy's ftype: butter, cheby1, cheby2, ellip, bessel
    band_type: str  # lowpass, highpass, bandpass, bandstop
    prototype_order: int  # a band-pass or band-stop has twice this order
    cutoffs: tuple[float, ...]  # Hz
    passband_ripple: float | None = None  # dB, for cheby1 and ellip
    stopband_attenuation: float | None = None  # dB, for cheby2 and ellip


# With the Bessel band-pass in iir_filter_test.cpp, they cover: families whose numerators aren't
# 1, ±2, 1; every band type; a first-order section; 1 to 12 sections; and low cutoffs (theta, a
# 1 Hz high-pass, the ripple band), where float32 arithmetic would fail.
DESIGNS = [
    Design("butterworth_lowpass_300", "butter", "lowpass", 4, (300.0,)),
    Design("butterworth_lowpass_100_first_order", "butter", "lowpass", 1, (100.0,)),
    Design("butterworth_highpass_1", "butter", "highpass", 2, (1.0,)),
    Design("butterworth_bandpass_theta", "butter", "bandpass", 2, (4.0, 12.0)),
    Design("butterworth_bandstop_50", "butter", "bandstop", 2, (45.0, 55.0)),
    Design("butterworth_bandpass_spike_12_sections", "butter", "bandpass", 12, (300.0, 6000.0)),
    Design("chebyshev1_lowpass_6000", "cheby1", "lowpass", 6, (6000.0,), passband_ripple=1.0),
    Design(
        "chebyshev2_bandpass_ripple",
        "cheby2",
        "bandpass",
        4,
        (150.0, 250.0),
        stopband_attenuation=40.0,
    ),
    Design(
        "elliptic_bandpass_ripple",
        "ellip",
        "bandpass",
        4,
        (150.0, 250.0),
        passband_ripple=0.5,
        stopband_attenuation=40.0,
    ),
]


def design_sections(design: Design) -> np.ndarray:
    cutoffs = design.cutoffs[0] if len(design.cutoffs) == 1 else list(design.cutoffs)
    sos = signal.iirfilter(
        design.prototype_order,
        cutoffs,
        rp=design.passband_ripple,
        rs=design.stopband_attenuation,
        btype=design.band_type,
        ftype=design.family,
        fs=SAMPLING_RATE,
        output="sos",
    )
    # Each row is b0, b1, b2, a0, a1, a2; IirFilter's sections have a0 divided out.
    return sos / sos[:, 3:4]


def describe_design(design: Design) -> str:
    def json_number(value: float | None) -> str:
        return "null" if value is None else repr(float(value))

    cutoffs = ", ".join(repr(float(cutoff)) for cutoff in design.cutoffs)
    return (
        f'{{"family": "{design.family}", "band_type": "{design.band_type}", '
        f'"prototype_order": {design.prototype_order}, "cutoffs": [{cutoffs}], '
        f'"passband_ripple": {json_number(design.passband_ripple)}, '
        f'"stopband_attenuation": {json_number(design.stopband_attenuation)}}}'
    )


# repr() writes each double in its shortest form that reads back exactly, valid as a C++ literal.
def write_visitor_call(design: Design, sections: np.ndarray) -> str:
    lines = [
        f"    visitor.template operator()<IirFilterOptions<{len(sections)}>{{",
        f"        .design_rate = {SAMPLING_RATE!r},",
        "        .gain = 1.0,",
        "        .sections =",
        "            {",
        "                {",
    ]
    for b0, b1, b2, _, a1, a2 in sections:
        lines += [
            "                    {",
            f"                        .b0 = {float(b0)!r},",
            f"                        .b1 = {float(b1)!r},",
            f"                        .b2 = {float(b2)!r},",
            f"                        .a1 = {float(a1)!r},",
            f"                        .a2 = {float(a2)!r},",
            "                    },",
        ]
    lines += [
        "                },",
        "            },",
        f'    }}>("{design.name}",',
        f'        R"json({describe_design(design)})json");',
    ]
    return "\n".join(lines)


HEADER = """\
// Generated by scripts/python/design_iir_test_filters.py, which designs these filters with SciPy.
// Don't edit by hand: change the script and run it again.
#pragma once
#include <string_view>
#include "../processors/iir_filter.cpp"

// Calls visitor.operator()<options>(name, design) for each design, where `design` is a JSON object
// naming the filter the coefficients claim to be, for the comparison to redesign.
template <typename DesignVisitor>
void for_each_generated_design(DesignVisitor&& visitor) {
"""


def main() -> None:
    repository_root = Path(__file__).resolve().parents[2]
    output_path = repository_root / "src" / "tests" / "iir_filter_test_designs.cpp"
    calls = [write_visitor_call(design, design_sections(design)) for design in DESIGNS]
    output_path.write_text(HEADER + "\n".join(calls) + "\n}\n")
    print(f"{len(DESIGNS)} designs written to {output_path}")


if __name__ == "__main__":
    main()
