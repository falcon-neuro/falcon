// Whether a text fits on one line of a comment. A line break in it would end the comment, and
// what follows would be compiled as code.
[[nodiscard]] inline bool is_one_line(std::string_view text) {
    constexpr unsigned char first_printable_character = 0x20;
    return std::ranges::none_of(text, [](char character) {
        return static_cast<unsigned char>(character) < first_printable_character;
    });
}

// A space, a tab, or the end of a line.
[[nodiscard]] inline bool is_blank(char character) {
    return character == ' ' || character == '\t' || character == '\n' || character == '\r';
}

[[nodiscard]] inline std::string_view without_spaces_around(std::string_view text) {
    while (!text.empty() && is_blank(text.front())) {
        text.remove_prefix(1);
    }
    while (!text.empty() && is_blank(text.back())) {
        text.remove_suffix(1);
    }
    return text;
}

// The name a template parameter is declared with, e.g. Capacity for "int Capacity" and options
// for "EventLoggerOptions options = EventLoggerOptions{}".
[[nodiscard]] inline std::string_view template_parameter_name(std::string_view parameter) {
    const std::string_view declaration =
        without_spaces_around(parameter.substr(0, parameter.find('=')));
    std::size_t name_start = declaration.size();
    while (name_start > 0 && is_identifier_character(declaration.at(name_start - 1))) {
        --name_start;
    }
    return declaration.substr(name_start);
}

// What a type is given between its outermost angle brackets, split at the commas that aren't
// inside further brackets: "Spikes<Stream>" and "1" for "EventOutputBuffer<Spikes<Stream>, 1>".
// None for a type without angle brackets.
[[nodiscard]] inline std::vector<std::string> type_arguments(std::string_view type) {
    std::vector<std::string> arguments;
    const std::size_t open_position = type.find('<');
    const std::size_t close_position = type.rfind('>');
    if (open_position == std::string_view::npos || close_position == std::string_view::npos ||
        close_position < open_position) {
        return arguments;
    }
    const std::string_view inside =
        type.substr(open_position + 1, close_position - open_position - 1);
    int bracket_depth = 0;
    std::size_t argument_start = 0;
    for (std::size_t position = 0; position < inside.size(); ++position) {
        const char character = inside.at(position);
        if (character == '<' || character == '(' || character == '{') {
            ++bracket_depth;
        } else if (character == '>' || character == ')' || character == '}') {
            --bracket_depth;
        } else if (character == ',' && bracket_depth == 0) {
            arguments.emplace_back(
                without_spaces_around(inside.substr(argument_start, position - argument_start)));
            argument_start = position + 1;
        }
    }
    arguments.emplace_back(without_spaces_around(inside.substr(argument_start)));
    return arguments;
}

// The type a template parameter is declared with, e.g. FirFilterOptions for "FirFilterOptions
// options".
[[nodiscard]] inline std::string_view template_parameter_type(std::string_view parameter) {
    const std::string_view declaration =
        without_spaces_around(parameter.substr(0, parameter.find('=')));
    return without_spaces_around(
        declaration.substr(0, declaration.size() - template_parameter_name(parameter).size()));
}

// --- Options that are lists ---

// Where a text in double quotes ends, one past its closing quote; the whole text's end for one
// that isn't closed.
[[nodiscard]] inline std::size_t end_of_quoted(std::string_view text, std::size_t open_quote) {
    std::size_t position = open_quote + 1;
    while (position < text.size() && text.at(position) != '"') {
        // A backslash takes the character after it along, e.g. a quote that doesn't close the text.
        position += text.at(position) == '\\' ? std::size_t{2} : std::size_t{1};
    }
    return std::min(position + 1, text.size());
}

[[nodiscard]] inline bool opens_bracket(char character) {
    return character == '{' || character == '(' || character == '[';
}

[[nodiscard]] inline bool closes_bracket(char character) {
    return character == '}' || character == ')' || character == ']';
}

// A value as it is written on one line: outside a text in quotes, every run of blanks becomes one
// space, none stays behind an opening bracket or in front of a closing one or a comma, and a comma
// in front of a closing bracket goes. So a list that a person laid out over many lines is held as
// one that the UI could have written.
[[nodiscard]] inline std::string on_one_line_plainly(std::string_view text) {
    std::string plain;
    const auto drop_spaces_at_end = [&plain] {
        while (!plain.empty() && plain.back() == ' ') {
            plain.pop_back();
        }
    };
    std::size_t position = 0;
    while (position < text.size()) {
        const char character = text.at(position);
        if (character == '"') {
            const std::size_t quoted_end = end_of_quoted(text, position);
            plain += text.substr(position, quoted_end - position);
            position = quoted_end;
            continue;
        }
        ++position;
        if (is_blank(character)) {
            if (!plain.empty() && plain.back() != ' ' && !opens_bracket(plain.back())) {
                plain += ' ';
            }
            continue;
        }
        if (closes_bracket(character) || character == ',') {
            drop_spaces_at_end();
        }
        if (closes_bracket(character) && !plain.empty() && plain.back() == ',') {
            plain.pop_back();
            drop_spaces_at_end();
        }
        plain += character;
    }
    drop_spaces_at_end();
    return plain;
}

// A text split at the commas that stand outside every bracket and every text in quotes, each part
// without the blanks around it. A comma at the very end starts no part.
[[nodiscard]] inline std::vector<std::string> parts_between_commas(std::string_view text) {
    std::vector<std::string> parts;
    int bracket_depth = 0;
    std::size_t part_start = 0;
    std::size_t position = 0;
    while (position < text.size()) {
        const char character = text.at(position);
        if (character == '"') {
            position = end_of_quoted(text, position);
            continue;
        }
        if (opens_bracket(character)) {
            ++bracket_depth;
        } else if (closes_bracket(character)) {
            --bracket_depth;
        } else if (character == ',' && bracket_depth == 0) {
            parts.emplace_back(
                without_spaces_around(text.substr(part_start, position - part_start)));
            part_start = position + 1;
        }
        ++position;
    }
    const std::string_view last_part = without_spaces_around(text.substr(part_start));
    if (!last_part.empty()) {
        parts.emplace_back(last_part);
    }
    return parts;
}

// What stands between a text's braces, where the text is one braced list from its first character
// to its last. None for any other text, e.g. "{1}, {2}", whose first brace closes before the end.
[[nodiscard]] inline std::optional<std::string_view> inside_of_braces(std::string_view text) {
    const std::string_view braced = without_spaces_around(text);
    if (braced.size() < 2 || braced.front() != '{' || braced.back() != '}') {
        return std::nullopt;
    }
    int brace_depth = 0;
    std::size_t position = 0;
    while (position < braced.size()) {
        const char character = braced.at(position);
        if (character == '"') {
            position = end_of_quoted(braced, position);
            continue;
        }
        if (character == '{') {
            ++brace_depth;
        } else if (character == '}') {
            --brace_depth;
        }
        if (brace_depth == 0 && position + 1 < braced.size()) {
            return std::nullopt;
        }
        ++position;
    }
    return braced.substr(1, braced.size() - 2);
}

[[nodiscard]] inline bool is_list_option(const OptionDescription& option) {
    return std::string_view(option.type).starts_with("std::array<");
}

// Whether the elements of a list option are braced lists themselves, as a struct's are. They
// aren't where an element is a number, a yes or no, or a text.
[[nodiscard]] inline bool has_braced_elements(const OptionDescription& option) {
    constexpr std::array<std::string_view, 5> plain_element_types{
        "double", "float", "int", "bool", "Str",
    };
    const std::vector<std::string> list_type_arguments = type_arguments(option.type);
    return list_type_arguments.empty() ||
           !std::ranges::contains(plain_element_types, list_type_arguments.front());
}

// The elements of a list option's value, each as written, or none for a value that isn't a list
// in braces. A list may be written with its braces doubled, which a std::array takes and one of
// structs needs: the elements are then those of the inner braces. Where an element is itself a
// braced list, a single braced part counts as the inner braces only if its own first part is
// braced too; else it is the list's one element.
[[nodiscard]] inline std::optional<std::vector<std::string>> list_elements_of(
    std::string_view value, bool is_element_braced) {
    const std::optional<std::string_view> inside = inside_of_braces(value);
    if (!inside.has_value()) {
        return std::nullopt;
    }
    std::vector<std::string> elements = parts_between_commas(inside.value_or(std::string_view{}));
    while (elements.size() == 1) {
        const std::optional<std::string_view> inner = inside_of_braces(elements.front());
        if (!inner.has_value()) {
            break;
        }
        std::vector<std::string> inner_elements =
            parts_between_commas(inner.value_or(std::string_view{}));
        const bool is_inner_first_braced =
            !inner_elements.empty() && inside_of_braces(inner_elements.front()).has_value();
        if (is_element_braced && !is_inner_first_braced) {
            break;
        }
        elements = std::move(inner_elements);
    }
    return elements;
}

// Elements with a comma and a space between them.
[[nodiscard]] inline std::string joined_with_commas(const std::vector<std::string>& elements) {
    std::string joined;
    for (const std::string& element : elements) {
        joined += std::format("{}{}", joined.empty() ? "" : ", ", element);
    }
    return joined;
}

// A list's value as the graph holds it: its elements between one pair of braces.
[[nodiscard]] inline std::string held_list_of(const std::vector<std::string>& elements) {
    return std::format("{{{}}}", joined_with_commas(elements));
}

// A list's value as pipeline.cpp has it: its elements between two pairs of braces, which a
// std::array of structs needs and one of numbers takes too.
[[nodiscard]] inline std::string written_list_of(const std::vector<std::string>& elements) {
    return std::format("{{{{{}}}}}", joined_with_commas(elements));
}

// What a pipeline's text is written for. One to compile is refused while the graph isn't
// finished. One to keep is written all the same, so that no work is lost: a port that isn't
// connected is left out of its processor's call, and a template argument that nothing gives yet
// is written as its parameter's own name, e.g. InputStreamInfo, which doesn't compile.
enum class WritingFor : std::uint8_t { Compiling, Keeping };

// How far back through the connections a type is looked for, so that processors feeding each
// other in a circle end the search, and what the text is written for.
struct TypeSearch {
    std::size_t steps_left = 0;
    WritingFor purpose = WritingFor::Compiling;

    [[nodiscard]] TypeSearch one_step_further() const {
        return {.steps_left = steps_left - 1, .purpose = purpose};
    }
};

// A template parameter of a processor's type, with what the pipeline gives it once that is known.
struct TemplateArgument {
    std::string parameter_name;
    std::optional<std::string> text;
};

// What a processor's template parameters are given, or why that can't be worked out.
using TemplateArguments = std::expected<std::vector<TemplateArgument>, PipelineProblem>;

// Where the next word starts at or after a position, a word being a run of identifier characters;
// the text's size when there is none.
[[nodiscard]] inline std::size_t next_word_start(std::string_view text, std::size_t position) {
    while (position < text.size() && !is_identifier_character(text.at(position))) {
        ++position;
    }
    return position;
}

[[nodiscard]] inline std::size_t word_end_from(std::string_view text, std::size_t word_start) {
    std::size_t word_end = word_start;
    while (word_end < text.size() && is_identifier_character(text.at(word_end))) {
        ++word_end;
    }
    return word_end;
}

// Whether a text holds a word, e.g. the name of a template parameter in a port's type.
[[nodiscard]] inline bool holds_word(std::string_view text, std::string_view word) {
    std::size_t word_start = next_word_start(text, 0);
    while (word_start < text.size()) {
        const std::size_t word_end = word_end_from(text, word_start);
        if (text.substr(word_start, word_end - word_start) == word) {
            return true;
        }
        word_start = next_word_start(text, word_end);
    }
    return false;
}

// A port's type with each template parameter it names replaced by what the pipeline gives that
// parameter. A parameter that nothing is known for stays as it is.
[[nodiscard]] inline std::string with_parameters_replaced(
    std::string_view type, const std::vector<TemplateArgument>& arguments) {
    std::string replaced;
    std::size_t position = 0;
    while (position < type.size()) {
        const std::size_t word_start = next_word_start(type, position);
        replaced += type.substr(position, word_start - position);
        const std::size_t word_end = word_end_from(type, word_start);
        const std::string_view word = type.substr(word_start, word_end - word_start);
        const auto argument = std::ranges::find(arguments, word, &TemplateArgument::parameter_name);
        replaced += argument == arguments.end() ? std::string(word)
                                                : argument->text.value_or(std::string(word));
        position = word_end;
    }
    return replaced;
}

// The name of the stream that a processor starts, after the processor's own name, which is unique:
// SignalGeneratorStream for signal_generator, SignalGenerator2Stream for signal_generator_2.
[[nodiscard]] inline std::string stream_name_of(std::string_view processor_name) {
    std::string name;
    bool is_first_of_word = true;
    for (const char character : processor_name) {
        if (character == '_') {
            is_first_of_word = true;
            continue;
        }
        const bool is_small_letter = character >= 'a' && character <= 'z';
        name += is_first_of_word && is_small_letter ? static_cast<char>(character - 'a' + 'A')
                                                    : character;
        is_first_of_word = false;
    }
    return name + "Stream";
}

// A stream's rate as written in its type. A whole number gets ".0": the type takes a double, and
// a template argument isn't turned from a whole number into one.
[[nodiscard]] inline std::string rate_text_of(double rate) {
    std::string text = std::format("{}", rate);
    if (text.find_first_of(".e") == std::string::npos) {
        text += ".0";
    }
    return text;
}

// The streams that the pipeline's processors start, each as a line that names it.
[[nodiscard]] inline std::string stream_declarations_of(const PipelineGraph& graph) {
    std::string declarations;
    for (const GraphProcessor& processor : graph.processors) {
        if (processor.stream.has_value()) {
            declarations += std::format(
                "using {} = StreamInfo<{}, {}, float>;\n", stream_name_of(processor.name),
                processor.stream->channel_count, rate_text_of(processor.stream->rate));
        }
    }
    return declarations;
}

// The type of a processor's options as its template parameter names it, e.g. FirFilterOptions.
[[nodiscard]] inline std::string_view options_type_of(const ProcessorDescription& type) {
    for (const char* parameter : type.template_parameters) {
        if (template_parameter_name(parameter) == OPTIONS_PARAMETER_NAME) {
            return template_parameter_type(parameter);
        }
    }
    return "";
}

// A processor's options as the braces its type is written with. Every option is named, also one
// that has its default value, so that the file says all that the processor runs with. Options
// that hold a list are sized by it, so their type is written in front with the list's length,
// e.g. "FirFilterOptions<2>{.design_rate = 30000.0, .taps = {{0.5, 0.5}}}".
[[nodiscard]] inline std::string options_text(const GraphProcessor& processor) {
    std::string text = "{";
    std::optional<std::size_t> list_length;
    for (std::size_t option_index = 0; option_index < processor.type->options.size();
         ++option_index) {
        const OptionDescription& option = processor.type->options[option_index];
        std::string value = processor.option_values.at(option_index);
        if (is_list_option(option)) {
            const std::vector<std::string> elements =
                list_elements_of(value, has_braced_elements(option))
                    .value_or(std::vector<std::string>{});
            list_length = elements.size();
            value = written_list_of(elements);
        }
        text += std::format("{}.{} = {}", option_index == 0 ? "" : ", ", option.name, value);
    }
    text += '}';
    if (!list_length.has_value()) {
        return text;
    }
    return std::format("{}<{}>{}", options_type_of(*processor.type), list_length.value_or(0), text);
}

// The type of the buffer that an output of this type writes, e.g. "EventBuffer<ScheduledEvent, 1>"
// for "EventOutputBuffer<ScheduledEvent, 1>".
[[nodiscard]] inline WrittenText buffer_type_of(std::string_view resolved_output_type_text) {
    constexpr std::string_view event_output_start = "EventOutputBuffer<";
    constexpr std::string_view sample_output_start = "SampleOutputBuffer<";
    if (resolved_output_type_text.starts_with(event_output_start)) {
        return std::format("EventBuffer<{}",
                           resolved_output_type_text.substr(event_output_start.size()));
    }
    if (resolved_output_type_text.starts_with(sample_output_start)) {
        return std::format("SampleBuffer<{}",
                           resolved_output_type_text.substr(sample_output_start.size()));
    }
    return std::unexpected(PipelineProblem{
        .title = "An output has no buffer",
        .body =
            std::format("no buffer is known for an output of type {}", resolved_output_type_text),
        .processor_name = {},
    });
}

// A problem that was found without knowing its processor, with that processor's name.
[[nodiscard]] inline PipelineProblem problem_of_processor(PipelineProblem problem,
                                                          const GraphProcessor& processor) {
    problem.processor_name = processor.name;
    return problem;
}

// Gives a processor's template parameters what one connection into it says about them: where the
// input's type names a parameter, the parameter is what the connected output's type has at the
// same place. Returns why not, when two connections say different things of one parameter.
[[nodiscard]] inline std::optional<PipelineProblem> bind_from_connection(
    std::vector<TemplateArgument>& arguments, const PortDescription& input_port,
    std::string_view output_type, const GraphProcessor& processor) {
    const std::vector<std::string> input_arguments = type_arguments(input_port.type);
    const std::vector<std::string> output_arguments = type_arguments(output_type);
    const std::size_t shared_count = std::min(input_arguments.size(), output_arguments.size());
    for (std::size_t position = 0; position < shared_count; ++position) {
        const auto argument = std::ranges::find(arguments, input_arguments.at(position),
                                                &TemplateArgument::parameter_name);
        // Anything but a parameter's name is a fixed part of the input's type, which the compiler
        // holds against the output's.
        if (argument == arguments.end()) {
            continue;
        }
        const std::string& given = output_arguments.at(position);
        if (argument->text.has_value() && *argument->text != given) {
            return PipelineProblem{
                .title = "Two connections disagree",
                .body = std::format("two of its connections give its type's {} differently, as {} "
                                    "and as {}",
                                    argument->parameter_name, *argument->text, given),
                .processor_name = processor.name,
            };
        }
        argument->text = given;
    }
    return std::nullopt;
}

[[nodiscard]] inline TemplateArguments template_arguments_of(const PipelineGraph& graph,
                                                             const GraphProcessor& processor,
                                                             TypeSearch search);

// An output's type with its processor's template parameters replaced by what the pipeline gives
// them, e.g. "EventOutputBuffer<ScheduledEvent, 1>". steps_left bounds how far back through the
// connections this looks, so that processors feeding each other in a circle end in a refusal.
[[nodiscard]] inline WrittenText resolved_output_type(const PipelineGraph& graph,
                                                      const OutputReference& output,
                                                      TypeSearch search) {
    const GraphProcessor* processor = graph.find_processor(output.processor);
    const PortDescription* port =
        graph.find_port(output.processor, output.port, PortDirection::Output);
    if (processor == nullptr || port == nullptr) {
        return std::unexpected(PipelineProblem{
            .title = "A connection has no start",
            .body = "a connection starts at an output the graph doesn't hold",
            .processor_name = {},
        });
    }
    const bool is_for_compiling = search.purpose == WritingFor::Compiling;
    if (search.steps_left == 0) {
        if (!is_for_compiling) {
            return std::string(port->type);
        }
        return std::unexpected(PipelineProblem{
            .title = "Processors feed each other in a circle",
            .body = "its type follows from processors that feed each other in a circle",
            .processor_name = processor->name,
        });
    }
    const TemplateArguments arguments =
        template_arguments_of(graph, *processor, search.one_step_further());
    if (!arguments.has_value()) {
        return std::unexpected(arguments.error());
    }
    for (const TemplateArgument& argument : *arguments) {
        if (is_for_compiling && !argument.text.has_value() &&
            holds_word(port->type, argument.parameter_name)) {
            return std::unexpected(PipelineProblem{
                .title = "An input isn't connected",
                .body = std::format("nothing connected to it gives its type's {}, which its "
                                    "output {} needs",
                                    argument.parameter_name, port->name),
                .processor_name = processor->name,
            });
        }
    }
    return with_parameters_replaced(port->type, *arguments);
}

// The list of slots that a port which takes several connections gives its processor's type: a
// name and a kind for each connection into it, in their order, e.g. `Slots<Slot<"ripples",
// EventBuffer<Ripple, 1>>>`.
[[nodiscard]] inline WrittenText slots_text_of(const PipelineGraph& graph,
                                               const GraphProcessor& processor,
                                               const PortDescription& port, TypeSearch search) {
    std::string slots;
    const InputReference input{.processor = processor.id, .port = port.name};
    for (const GraphConnection* connection : graph.connections_into(input)) {
        const WrittenText output_type = resolved_output_type(graph, connection->output, search);
        if (!output_type.has_value()) {
            return output_type;
        }
        const WrittenText kind = buffer_type_of(*output_type);
        if (!kind.has_value()) {
            return std::unexpected(problem_of_processor(kind.error(), processor));
        }
        slots += std::format("{}Slot<\"{}\", {}>", slots.empty() ? "" : ", ",
                             graph.name_of_output(connection->output), *kind);
    }
    return std::format("Slots<{}>", slots);
}

// Gives a processor's template parameters the list of slots of each of its ports that take
// several connections. Returns why not, for a port whose list the type doesn't take.
[[nodiscard]] inline std::optional<PipelineProblem> bind_slots(
    std::vector<TemplateArgument>& arguments, const PipelineGraph& graph,
    const GraphProcessor& processor, TypeSearch search) {
    for (const PortDescription& port : processor.type->ports) {
        if (!port.has_slots || port.direction != PortDirection::Input) {
            continue;
        }
        const std::vector<std::string> port_type_arguments = type_arguments(port.type);
        const auto argument = port_type_arguments.empty()
                                  ? arguments.end()
                                  : std::ranges::find(arguments, port_type_arguments.front(),
                                                      &TemplateArgument::parameter_name);
        if (argument == arguments.end()) {
            return PipelineProblem{
                .title = "A port's connections have no place",
                .body = std::format("the type of a {} takes no list of slots for its port {}",
                                    processor.type->name, port.name),
                .processor_name = processor.name,
            };
        }
        const WrittenText slots = slots_text_of(graph, processor, port, search);
        if (!slots.has_value()) {
            return slots.error();
        }
        argument->text = *slots;
    }
    return std::nullopt;
}

// What each template parameter of a processor's type is given: its options, the stream it starts,
// the slots of a port that takes several connections, and what follows from the outputs connected
// to its other inputs. A parameter that nothing gives stays without a text.
[[nodiscard]] inline TemplateArguments template_arguments_of(const PipelineGraph& graph,
                                                             const GraphProcessor& processor,
                                                             TypeSearch search) {
    std::vector<TemplateArgument> arguments;
    for (const char* parameter : processor.type->template_parameters) {
        const std::string_view parameter_name = template_parameter_name(parameter);
        std::optional<std::string> given;
        if (parameter_name == OPTIONS_PARAMETER_NAME) {
            given = options_text(processor);
        } else if (parameter_name == OUTPUT_STREAM_PARAMETER_NAME && processor.stream.has_value()) {
            given = stream_name_of(processor.name);
        }
        arguments.push_back({.parameter_name = std::string(parameter_name), .text = given});
    }
    for (const GraphConnection& connection : graph.connections) {
        const PortDescription* input_port =
            graph.find_port(processor.id, connection.input.port, PortDirection::Input);
        // A port that takes several connections names no parameter that one of them alone gives.
        if (connection.input.processor != processor.id || input_port == nullptr ||
            input_port->has_slots) {
            continue;
        }
        const WrittenText output_type = resolved_output_type(graph, connection.output, search);
        if (!output_type.has_value()) {
            return std::unexpected(output_type.error());
        }
        if (const std::optional<PipelineProblem> conflict =
                bind_from_connection(arguments, *input_port, *output_type, processor)) {
            return std::unexpected(*conflict);
        }
    }
    if (const std::optional<PipelineProblem> refusal =
            bind_slots(arguments, graph, processor, search)) {
        return std::unexpected(*refusal);
    }
    return arguments;
}

// A processor's type as its variable is declared with, e.g. "EventLogger<ScheduledEvent, 1,
// {.style = LoggingStyle::EveryEvent}>".
[[nodiscard]] inline WrittenText type_text_of(const GraphProcessor& processor,
                                              const std::vector<TemplateArgument>& arguments,
                                              WritingFor purpose) {
    std::string text = processor.type->name;
    for (std::size_t argument_index = 0; argument_index < arguments.size(); ++argument_index) {
        const TemplateArgument& argument = arguments.at(argument_index);
        if (!argument.text.has_value() && purpose == WritingFor::Compiling) {
            return std::unexpected(PipelineProblem{
                .title = "An input isn't connected",
                .body = std::format("nothing connected to it gives its type's {}",
                                    argument.parameter_name),
                .processor_name = processor.name,
            });
        }
        text += argument_index == 0 ? "<" : ", ";
        text += argument.text.value_or(argument.parameter_name);
    }
    if (!arguments.empty()) {
        text += '>';
    }
    return text;
}

// The name of the buffer an output writes: the name of what the output gives, so that it stays
// the same whichever processors read it.
[[nodiscard]] inline std::string buffer_name_of(const PipelineGraph& graph,
                                                const OutputReference& output) {
    return std::format("{}_buffer", graph.name_of_output(output));
}

[[nodiscard]] inline bool has_reader(const PipelineGraph& graph, const OutputReference& output) {
    return std::ranges::any_of(graph.connections, [&output](const GraphConnection& connection) {
        return connection.output == output;
    });
}

// The core a connection's reader lies on, or none for a reader the graph doesn't hold.
[[nodiscard]] inline std::optional<int> reader_core_of(const PipelineGraph& graph,
                                                       const GraphConnection& connection) {
    const GraphProcessor* reader = graph.find_processor(connection.input.processor);
    return reader == nullptr ? std::nullopt : std::optional<int>(reader->core_number);
}

// The cores other than its own on which an output's readers lie, each once, the lowest first. A
// ring carries the output to each of them.
[[nodiscard]] inline std::vector<int> ring_cores_of(const PipelineGraph& graph,
                                                    const OutputReference& output) {
    std::vector<int> ring_cores;
    const GraphProcessor* writer = graph.find_processor(output.processor);
    if (writer == nullptr) {
        return ring_cores;
    }
    for (const GraphConnection& connection : graph.connections) {
        const std::optional<int> reader_core = reader_core_of(graph, connection);
        if (connection.output == output && reader_core.has_value() &&
            *reader_core != writer->core_number &&
            !std::ranges::contains(ring_cores, *reader_core)) {
            ring_cores.push_back(*reader_core);
        }
    }
    std::ranges::sort(ring_cores);
    return ring_cores;
}

[[nodiscard]] inline bool has_reader_on_its_core(const PipelineGraph& graph,
                                                 const OutputReference& output) {
    const GraphProcessor* writer = graph.find_processor(output.processor);
    return writer != nullptr &&
           std::ranges::any_of(graph.connections, [&](const GraphConnection& connection) {
               return connection.output == output &&
                      reader_core_of(graph, connection) == writer->core_number;
           });
}

// Whether an output writes straight into a ring: it has one ring, and no reader on its own core,
// so nothing has to be copied from a buffer into the ring.
[[nodiscard]] inline bool writes_straight_into_ring(const PipelineGraph& graph,
                                                    const OutputReference& output) {
    return !has_reader_on_its_core(graph, output) && ring_cores_of(graph, output).size() == 1;
}

// An output of a processor, and a core that reads it through a ring.
struct RingPlace {
    const GraphProcessor& writer;
    std::string_view output_name;
    int reader_core_number = 0;
};

// The name of a ring: the name of what its writer's output gives, and the core that reads it,
// since an output has a ring for each such core and the log names the ring that is full.
[[nodiscard]] inline std::string ring_name_of(const PipelineGraph& graph, const RingPlace& ring) {
    const OutputReference output{
        .processor = ring.writer.id,
        .port = std::string(ring.output_name),
    };
    return std::format("{}_ring_to_core{}", graph.name_of_output(output), ring.reader_core_number);
}

// The number of slots of a ring: the largest that the user set on a connection through it, or
// the usual number where none is set.
[[nodiscard]] inline int ring_slot_count_of(const PipelineGraph& graph, const RingPlace& ring) {
    const OutputReference output{
        .processor = ring.writer.id,
        .port = std::string(ring.output_name),
    };
    std::optional<int> largest_set;
    for (const GraphConnection& connection : graph.connections) {
        if (connection.output == output && connection.ring_slot_count.has_value() &&
            reader_core_of(graph, connection) == ring.reader_core_number) {
            largest_set = std::max(largest_set.value_or(0), connection.ring_slot_count.value_or(0));
        }
    }
    const auto reader_core =
        std::ranges::find(graph.cores, ring.reader_core_number, &GraphCore::number);
    const bool is_reader_realtime = reader_core == graph.cores.end() || reader_core->is_realtime;
    return largest_set.value_or(usual_ring_slot_count(is_reader_realtime));
}

// The type of the ring that carries what an output of this type writes, e.g.
// "EventRing<ScheduledEvent, 1, 64>" for "EventOutputBuffer<ScheduledEvent, 1>" and 64 slots.
[[nodiscard]] inline WrittenText ring_type_of(std::string_view resolved_output_type_text,
                                              int slot_count) {
    const WrittenText buffer_type = buffer_type_of(resolved_output_type_text);
    if (!buffer_type.has_value()) {
        return buffer_type;
    }
    // A buffer's type is "EventBuffer<...>" or "SampleBuffer<...>".
    constexpr std::string_view buffer_word = "Buffer<";
    const std::size_t word_position = buffer_type->find(buffer_word);
    const std::size_t inside_start = word_position + buffer_word.size();
    return std::format("{}Ring<{}, {}>", buffer_type->substr(0, word_position),
                       buffer_type->substr(inside_start, buffer_type->size() - inside_start - 1),
                       slot_count);
}

// The rings that carry a processor's outputs to other cores, each as a line that declares it.
[[nodiscard]] inline WrittenText ring_declarations_of(const PipelineGraph& graph,
                                                      const GraphProcessor& processor,
                                                      WritingFor purpose) {
    std::string declarations;
    for (const PortDescription& port : processor.type->ports) {
        const OutputReference output{.processor = processor.id, .port = port.name};
        const std::vector<int> ring_cores = port.direction == PortDirection::Output
                                                ? ring_cores_of(graph, output)
                                                : std::vector<int>{};
        if (ring_cores.empty()) {
            continue;
        }
        const WrittenText output_type = resolved_output_type(
            graph, output, {.steps_left = graph.processors.size(), .purpose = purpose});
        if (!output_type.has_value()) {
            return output_type;
        }
        for (const int ring_core : ring_cores) {
            const RingPlace ring{
                .writer = processor,
                .output_name = port.name,
                .reader_core_number = ring_core,
            };
            const WrittenText ring_type =
                ring_type_of(*output_type, ring_slot_count_of(graph, ring));
            if (!ring_type.has_value()) {
                return std::unexpected(problem_of_processor(ring_type.error(), processor));
            }
            declarations +=
                std::format("{0} {1}{{\"{1}\"}};\n", *ring_type, ring_name_of(graph, ring));
        }
    }
    return declarations;
}

// The order in which a core's loop calls its processors. A processor is called once every
// processor of the core that it reads samples or events from has been called. Of those that may
// be called, the first in the core's list that reads from the one called last comes next, so that
// a chain is run through from its top to its bottom while its data is still in the cache; where
// none reads from it, the first in the core's list comes next.
[[nodiscard]] inline std::expected<std::vector<ProcessorId>, PipelineProblem> call_order_of(
    const PipelineGraph& graph, const GraphCore& core) {
    const std::vector<PlacingConnection> placing_connections =
        placing_connections_of(graph, core.processors);
    const std::size_t place_count = core.processors.size();
    std::vector<bool> is_called(place_count, false);
    std::vector<ProcessorId> call_order;
    std::optional<std::size_t> last_called_place;

    const auto may_be_called = [&](std::size_t place) {
        return !is_called.at(place) &&
               std::ranges::none_of(placing_connections, [&](const PlacingConnection& connection) {
                   return connection.reader_place == place &&
                          !is_called.at(connection.writer_place);
               });
    };
    const auto reads_from_last_called = [&](std::size_t place) {
        return std::ranges::any_of(placing_connections, [&](const PlacingConnection& connection) {
            return connection.reader_place == place && connection.writer_place == last_called_place;
        });
    };

    while (call_order.size() < place_count) {
        std::optional<std::size_t> next_place;
        for (std::size_t place = 0; place < place_count && !next_place.has_value(); ++place) {
            if (may_be_called(place) && reads_from_last_called(place)) {
                next_place = place;
            }
        }
        for (std::size_t place = 0; place < place_count && !next_place.has_value(); ++place) {
            if (may_be_called(place)) {
                next_place = place;
            }
        }
        // The connections that order the calls run in no circle, so one processor may always be
        // called.
        if (!next_place.has_value()) {
            return std::unexpected(PipelineProblem{
                .title = "A core's processors have no order",
                .body = std::format("core {}: no order of its processors' calls was found",
                                    core.number),
                .processor_name = {},
            });
        }
        is_called.at(*next_place) = true;
        last_called_place = next_place;
        call_order.push_back(core.processors.at(*next_place));
    }
    return call_order;
}

// The buffers that a processor's outputs write, each as a line that declares it. An output that
// nothing reads gets none, and neither does one that writes straight into its ring. A buffer is
// given the rings that carry it to other cores.
[[nodiscard]] inline WrittenText buffer_declarations_of(const PipelineGraph& graph,
                                                        const GraphProcessor& processor,
                                                        WritingFor purpose) {
    std::string declarations;
    for (const PortDescription& port : processor.type->ports) {
        const OutputReference output{.processor = processor.id, .port = port.name};
        if (port.direction != PortDirection::Output || !has_reader(graph, output) ||
            writes_straight_into_ring(graph, output)) {
            continue;
        }
        const WrittenText output_type = resolved_output_type(
            graph, output, {.steps_left = graph.processors.size(), .purpose = purpose});
        if (!output_type.has_value()) {
            return output_type;
        }
        const WrittenText buffer_type = buffer_type_of(*output_type);
        if (!buffer_type.has_value()) {
            return std::unexpected(problem_of_processor(buffer_type.error(), processor));
        }
        std::string ring_names;
        for (const int ring_core : ring_cores_of(graph, output)) {
            ring_names += std::format("{}{}", ring_names.empty() ? "" : ", ",
                                      ring_name_of(graph, {
                                                              .writer = processor,
                                                              .output_name = port.name,
                                                              .reader_core_number = ring_core,
                                                          }));
        }
        declarations += std::format("    {} {}{};\n", *buffer_type, buffer_name_of(graph, output),
                                    ring_names.empty() ? "" : std::format("{{{}}}", ring_names));
    }
    return declarations;
}

// The buffer or ring that an output of a processor is given in its call, or none for an output
// that nothing reads, which the call leaves out.
[[nodiscard]] inline std::optional<std::string> given_to_output(const PipelineGraph& graph,
                                                                const GraphProcessor& processor,
                                                                const PortDescription& port) {
    const OutputReference output{.processor = processor.id, .port = port.name};
    if (!has_reader(graph, output)) {
        return std::nullopt;
    }
    if (writes_straight_into_ring(graph, output)) {
        return ring_name_of(graph, {
                                       .writer = processor,
                                       .output_name = port.name,
                                       .reader_core_number = ring_cores_of(graph, output).front(),
                                   });
    }
    return buffer_name_of(graph, output);
}

// The buffer or ring through which a connection reaches its reader: its writer's buffer where the
// writer lies on the reader's core, and else the ring that carries the writer's output to that
// core. None for a writer the graph doesn't hold.
[[nodiscard]] inline std::optional<std::string> source_of_connection(
    const PipelineGraph& graph, const GraphProcessor& reader, const GraphConnection& connection) {
    const GraphProcessor* writer = graph.find_processor(connection.output.processor);
    if (writer == nullptr) {
        return std::nullopt;
    }
    if (writer->core_number == reader.core_number) {
        return buffer_name_of(graph, connection.output);
    }
    return ring_name_of(graph, {
                                   .writer = *writer,
                                   .output_name = connection.output.port,
                                   .reader_core_number = reader.core_number,
                               });
}

// What an input of a processor is given in its call: the buffer or ring of its connection, or, for
// a port that takes several connections, theirs in braces and in their order. None for an input
// that nothing is connected to, which the call leaves out.
[[nodiscard]] inline std::optional<std::string> given_to_input(const PipelineGraph& graph,
                                                               const GraphProcessor& processor,
                                                               const PortDescription& port) {
    const std::vector<const GraphConnection*> connections =
        graph.connections_into({.processor = processor.id, .port = port.name});
    if (connections.empty()) {
        return std::nullopt;
    }
    if (!port.has_slots) {
        return source_of_connection(graph, processor, *connections.front());
    }
    std::string sources;
    for (const GraphConnection* connection : connections) {
        const std::optional<std::string> source =
            source_of_connection(graph, processor, *connection);
        if (!source.has_value()) {
            return std::nullopt;
        }
        sources += std::format("{}{}", sources.empty() ? "" : ", ", *source);
    }
    return std::format("{{{}}}", sources);
}

// How the line that declares a processor ends and how the line that calls it begins. A line of a
// written pipeline.cpp is known as a processor's by these two (see processors_of_lines).
[[nodiscard]] inline std::string declaration_end_of(std::string_view processor_name) {
    return std::format(" {}{{\"{}\"}};", processor_name, processor_name);
}

[[nodiscard]] inline std::string call_start_of(std::string_view processor_name) {
    return std::format("{}.process(", processor_name);
}

// The line of a core's loop that calls a processor, with its ports in the order its type
// declares them, which is the order the compiler expects them in.
[[nodiscard]] inline std::string call_text_of(const PipelineGraph& graph,
                                              const GraphProcessor& processor) {
    std::string given_buffers;
    for (const PortDescription& port : processor.type->ports) {
        const std::optional<std::string> buffer = port.direction == PortDirection::Output
                                                      ? given_to_output(graph, processor, port)
                                                      : given_to_input(graph, processor, port);
        if (buffer.has_value()) {
            given_buffers +=
                std::format("{}.{} = {}", given_buffers.empty() ? "" : ", ", port.name, *buffer);
        }
    }
    return std::format("        {}{{{}}});\n", call_start_of(processor.name), given_buffers);
}

// The function that a core runs: its processors, the buffers they write, and its loop.
[[nodiscard]] inline WrittenText core_function_text_of(const PipelineGraph& graph,
                                                       const GraphCore& core, WritingFor purpose) {
    const std::expected<std::vector<ProcessorId>, PipelineProblem> call_order =
        call_order_of(graph, core);
    if (!call_order.has_value()) {
        return std::unexpected(call_order.error());
    }
    std::string processor_declarations;
    std::string buffer_declarations;
    std::string calls;
    for (const ProcessorId processor_id : *call_order) {
        const GraphProcessor* processor = graph.find_processor(processor_id);
        if (processor == nullptr) {
            return std::unexpected(PipelineProblem{
                .title = "A core lists an unknown processor",
                .body =
                    std::format("core {} lists a processor the graph doesn't hold", core.number),
                .processor_name = {},
            });
        }
        const TemplateArguments arguments = template_arguments_of(
            graph, *processor, {.steps_left = graph.processors.size(), .purpose = purpose});
        if (!arguments.has_value()) {
            return std::unexpected(arguments.error());
        }
        const WrittenText type_text = type_text_of(*processor, *arguments, purpose);
        if (!type_text.has_value()) {
            return type_text;
        }
        const WrittenText buffers = buffer_declarations_of(graph, *processor, purpose);
        if (!buffers.has_value()) {
            return buffers;
        }
        processor_declarations +=
            std::format("    {}{}\n", *type_text, declaration_end_of(processor->name));
        buffer_declarations += *buffers;
        calls += call_text_of(graph, *processor);
    }
    return std::format("void core{}() {{\n{}{}{}\n    while (next_pass()) {{\n{}    }}\n}}\n",
                       core.number, processor_declarations, buffer_declarations.empty() ? "" : "\n",
                       buffer_declarations, calls);
}

[[nodiscard]] inline std::string header_text_of(const PipelineGraph& graph) {
    return std::format("{}\n// {}: {}\n// {}: {}\n// {}: {}\n{}\n", PIPELINE_HEADER_START,
                       PIPELINE_HEADER_NAME_KEY, graph.name, PIPELINE_HEADER_DESCRIPTION_KEY,
                       graph.description, PIPELINE_HEADER_VERSION_KEY, VERSION_OF_THIS_FALCON,
                       PIPELINE_HEADER_END);
}

// The engine and the file of every kind of processor the pipeline holds, each named from the
// repository's src folder.
[[nodiscard]] inline std::string includes_text_of(const PipelineGraph& graph) {
    std::vector<std::string> files{"core/engine.cpp"};
    for (const GraphProcessor& processor : graph.processors) {
        files.emplace_back(processor.type->file);
    }
    std::ranges::sort(files);
    const auto repeated = std::ranges::unique(files);
    files.erase(repeated.begin(), repeated.end());
    std::string text;
    for (const std::string& file : files) {
        text += std::format("#include \"{}\"\n", file);
    }
    return text;
}

[[nodiscard]] inline std::string main_text_of(const std::vector<const GraphCore*>& cores) {
    std::string core_list;
    for (const GraphCore* core : cores) {
        core_list +=
            std::format("        {{.core_number = {}, .entry_point = core{}{}}},\n", core->number,
                        core->number, core->is_realtime ? "" : ", .is_realtime = false");
    }
    return std::format(
        "int main(int argument_count, char** arguments) {{\n"
        "    return run_on_cores(argument_count, arguments, {{\n{}    }});\n}}\n",
        core_list);
}

// Why the stream that a processor starts can't be written, or none if it can, and for a processor
// that starts no stream.
[[nodiscard]] inline std::optional<PipelineProblem> refusal_of_stream(
    const PipelineGraph& graph, const GraphProcessor& processor) {
    if (processor.type->starts_stream != processor.stream.has_value()) {
        return PipelineProblem{
            .title = "A stream is missing or one too many",
            .body =
                std::format("a {} {}, and the graph holds {} for it", processor.type->name,
                            processor.type->starts_stream ? "starts a stream" : "starts no stream",
                            processor.stream.has_value() ? "one" : "none"),
            .processor_name = processor.name,
        };
    }
    if (!processor.stream.has_value()) {
        return std::nullopt;
    }
    const bool is_rate_usable = std::isfinite(processor.stream->rate) && processor.stream->rate > 0;
    if (processor.stream->channel_count < 1 || !is_rate_usable) {
        return PipelineProblem{
            .title = "A stream's values are out of range",
            .body = "its stream needs one channel at least and a rate above 0",
            .processor_name = processor.name,
        };
    }
    const std::string stream_name = stream_name_of(processor.name);
    for (const GraphProcessor& other : graph.processors) {
        if (other.id != processor.id && other.stream.has_value() &&
            stream_name_of(other.name) == stream_name) {
            return PipelineProblem{
                .title = "Two streams would get one name",
                .body = std::format("{} and {}: the streams they start would both be named {}",
                                    processor.name, other.name, stream_name),
                .processor_name = processor.name,
            };
        }
    }
    return std::nullopt;
}

// Whether a text can be a slot's name, which the engine checks when the file is compiled.
[[nodiscard]] inline bool is_slot_name(std::string_view text) {
    return !text.empty() && std::ranges::all_of(text, is_identifier_character);
}

// Why a processor's ports that take several connections can't be written, or none if they can,
// and for a processor without such a port.
[[nodiscard]] inline std::optional<PipelineProblem> refusal_of_slots(
    const GraphProcessor& processor) {
    for (const PortDescription& port : processor.type->ports) {
        if (port.has_slots && port.direction == PortDirection::Output) {
            return PipelineProblem{
                .title = "An output takes several connections",
                .body = std::format("the writer doesn't write an output that takes several "
                                    "connections, as {} of a {} is",
                                    port.name, processor.type->name),
                .processor_name = processor.name,
            };
        }
    }
    return std::nullopt;
}

// Why the names of the pipeline's outputs can't be written, or none if they can. A name is the
// start of its output's buffer and rings, so it has to be one that a variable can have, and what
// processors make of two outputs, e.g. a Recorder's file, couldn't tell two of one name apart.
[[nodiscard]] inline std::optional<PipelineProblem> refusal_of_output_names(
    const PipelineGraph& graph) {
    struct NamedOutput {
        std::string name;
        std::string place;  // its processor and port, for the refusal
    };
    std::vector<NamedOutput> named_outputs;
    for (const GraphProcessor& processor : graph.processors) {
        for (const PortDescription& port : processor.type->ports) {
            if (port.direction != PortDirection::Output) {
                continue;
            }
            NamedOutput output{
                .name = graph.name_of_output({.processor = processor.id, .port = port.name}),
                .place = std::format("{}.{}", processor.name, port.name),
            };
            if (!is_identifier(output.name)) {
                return PipelineProblem{
                    .title = "An output's name can't be used",
                    .body = std::format("{} is named \"{}\", which can't be an output's name: a "
                                        "name holds letters, digits and _ only, and doesn't start "
                                        "with a digit",
                                        output.place, output.name),
                    .processor_name = processor.name,
                };
            }
            const auto same_name =
                std::ranges::find(named_outputs, output.name, &NamedOutput::name);
            if (same_name != named_outputs.end()) {
                return PipelineProblem{
                    .title = "Two outputs have one name",
                    .body = std::format("{} and {} are both named {}", same_name->place,
                                        output.place, output.name),
                    .processor_name = processor.name,
                };
            }
            named_outputs.push_back(std::move(output));
        }
    }
    return std::nullopt;
}

// Why a processor's options that are lists can't be written, or none if they can, and for a
// processor without one.
[[nodiscard]] inline std::optional<PipelineProblem> refusal_of_lists(
    const GraphProcessor& processor) {
    std::size_t list_count = 0;
    for (std::size_t option_index = 0; option_index < processor.type->options.size();
         ++option_index) {
        const OptionDescription& option = processor.type->options[option_index];
        if (!is_list_option(option)) {
            continue;
        }
        ++list_count;
        const std::string& value = processor.option_values.at(option_index);
        if (!list_elements_of(value, has_braced_elements(option)).has_value()) {
            return PipelineProblem{
                .title = "An option isn't a list",
                .body = std::format("its option {} must be a list in braces, and is `{}`",
                                    option.name, value),
                .processor_name = processor.name,
            };
        }
    }
    if (list_count > 1) {
        return PipelineProblem{
            .title = "Two options are lists",
            .body = "the writer doesn't write a processor with two options that are lists",
            .processor_name = processor.name,
        };
    }
    const std::string_view options_type = options_type_of(*processor.type);
    if (list_count == 1 && (options_type.empty() || options_type == "auto")) {
        return PipelineProblem{
            .title = "The options' type isn't known",
            .body = std::format("the type of a {}'s options isn't known, and options with a list "
                                "are written with it",
                                processor.type->name),
            .processor_name = processor.name,
        };
    }
    return std::nullopt;
}

// Why a processor can't be written, or none if it can.
[[nodiscard]] inline std::optional<PipelineProblem> refusal_of_processor(
    const PipelineGraph& graph, const GraphProcessor& processor) {
    if (processor.type == nullptr) {
        return PipelineProblem{
            .title = "A processor has no kind",
            .body = "the graph doesn't say what kind of processor it is",
            .processor_name = processor.name,
        };
    }
    if (!is_identifier(processor.name)) {
        return PipelineProblem{
            .title = "A processor's name can't be used",
            .body = std::format("\"{}\" can't be a processor's name: a name holds letters, digits "
                                "and _ only, and doesn't start with a digit",
                                processor.name),
            .processor_name = processor.name,
        };
    }
    const auto same_name_count =
        std::ranges::count(graph.processors, processor.name, &GraphProcessor::name);
    if (same_name_count > 1) {
        return PipelineProblem{
            .title = "Two processors have one name",
            .body = std::format("{} processors have this name", same_name_count),
            .processor_name = processor.name,
        };
    }
    if (processor.option_values.size() != processor.type->options.size()) {
        return PipelineProblem{
            .title = "Options and their values don't match",
            .body = std::format("it holds {} option values, and its type has {} options",
                                processor.option_values.size(), processor.type->options.size()),
            .processor_name = processor.name,
        };
    }
    if (std::optional<PipelineProblem> refusal = refusal_of_stream(graph, processor)) {
        return refusal;
    }
    if (std::optional<PipelineProblem> refusal = refusal_of_slots(processor)) {
        return refusal;
    }
    return refusal_of_lists(processor);
}

// Why a connection can't be written, or none if it can.
[[nodiscard]] inline std::optional<PipelineProblem> refusal_of_connection(
    const PipelineGraph& graph, const GraphConnection& connection) {
    const GraphProcessor* writer = graph.find_processor(connection.output.processor);
    const GraphProcessor* reader = graph.find_processor(connection.input.processor);
    const PortDescription* output_port =
        graph.find_port(connection.output.processor, connection.output.port, PortDirection::Output);
    const PortDescription* input_port =
        graph.find_port(connection.input.processor, connection.input.port, PortDirection::Input);
    if (writer == nullptr || reader == nullptr || output_port == nullptr || input_port == nullptr) {
        return PipelineProblem{
            .title = "A connection has a missing end",
            .body = "a connection has an end that the graph doesn't hold",
            .processor_name = {},
        };
    }
    const std::string ends = std::format("{}.{} to {}.{}", writer->name, output_port->name,
                                         reader->name, input_port->name);
    if (output_port->kind == PortKind::State) {
        return PipelineProblem{
            .title = "State values can't be compiled yet",
            .body = std::format("{}: the writer doesn't write a connection of a state value", ends),
            .processor_name = reader->name,
        };
    }
    return std::nullopt;
}

// Why a processor's ports can't be written as they are connected, or none if they can: a port
// that a graph may not leave unconnected has nothing connected to it. Its processor's call would
// lack a value for it, which the compiler refuses in words that tell a user nothing. A port
// that takes several connections says itself how many it needs.
[[nodiscard]] inline std::optional<PipelineProblem> refusal_of_unconnected_ports(
    const PipelineGraph& graph, const GraphProcessor& processor) {
    for (const PortDescription& port : processor.type->ports) {
        if (port.is_optional || port.has_slots) {
            continue;
        }
        const bool is_output = port.direction == PortDirection::Output;
        const bool is_connected =
            is_output
                ? has_reader(graph, {.processor = processor.id, .port = port.name})
                : !graph.connections_into({.processor = processor.id, .port = port.name}).empty();
        if (!is_connected) {
            return PipelineProblem{
                .title = is_output ? "An output isn't connected" : "An input isn't connected",
                .body =
                    std::format("its {} {} isn't connected to anything, and a {} needs it "
                                "connected",
                                is_output ? "output" : "input", port.name, processor.type->name),
                .processor_name = processor.name,
            };
        }
    }
    return std::nullopt;
}

// Why a graph can't be written, or none if it can. One that isn't finished is refused only when
// its text is to compile.
[[nodiscard]] inline std::optional<PipelineProblem> refusal_of(const PipelineGraph& graph,
                                                               WritingFor purpose) {
    const bool is_for_compiling = purpose == WritingFor::Compiling;
    if (!is_one_line(graph.name) || !is_one_line(graph.description)) {
        return PipelineProblem{
            .title = "The pipeline's name has a line break",
            .body = "the pipeline's name and its description must each fit on one line",
            .processor_name = {},
        };
    }
    if (graph.processors.empty() && is_for_compiling) {
        return PipelineProblem{
            .title = "The pipeline is empty",
            .body = "the pipeline holds no processor",
            .processor_name = {},
        };
    }
    for (const GraphProcessor& processor : graph.processors) {
        if (std::optional<PipelineProblem> refusal = refusal_of_processor(graph, processor)) {
            return refusal;
        }
    }
    for (const GraphConnection& connection : graph.connections) {
        if (std::optional<PipelineProblem> refusal = refusal_of_connection(graph, connection)) {
            return refusal;
        }
    }
    if (std::optional<PipelineProblem> refusal = refusal_of_output_names(graph)) {
        return refusal;
    }
    for (const GraphProcessor& processor : graph.processors) {
        if (!is_for_compiling) {
            break;
        }
        if (std::optional<PipelineProblem> refusal =
                refusal_of_unconnected_ports(graph, processor)) {
            return refusal;
        }
    }
    return std::nullopt;
}

// The text of a pipeline's pipeline.cpp for this purpose, or why the graph can't be written.
[[nodiscard]] inline WrittenText written_pipeline(const PipelineGraph& graph, WritingFor purpose) {
    if (std::optional<PipelineProblem> refusal = refusal_of(graph, purpose)) {
        return std::unexpected(*refusal);
    }
    std::vector<const GraphCore*> cores;
    for (const GraphCore& core : graph.cores) {
        if (!core.processors.empty()) {
            cores.push_back(&core);
        }
    }
    std::ranges::sort(cores, {}, &GraphCore::number);

    std::string text = header_text_of(graph) + includes_text_of(graph);
    const std::string stream_declarations = stream_declarations_of(graph);
    if (!stream_declarations.empty()) {
        text += "\n" + stream_declarations;
    }
    std::string ring_declarations;
    for (const GraphProcessor& processor : graph.processors) {
        const WrittenText rings = ring_declarations_of(graph, processor, purpose);
        if (!rings.has_value()) {
            return rings;
        }
        ring_declarations += *rings;
    }
    if (!ring_declarations.empty()) {
        text += "\n" + ring_declarations;
    }
    for (const GraphCore* core : cores) {
        const WrittenText core_function_text = core_function_text_of(graph, *core, purpose);
        if (!core_function_text.has_value()) {
            return core_function_text;
        }
        text += "\n" + *core_function_text;
    }
    text += "\n" + main_text_of(cores);
    return text;
}

// The text of a pipeline's pipeline.cpp to compile, or why the graph can't be written or isn't
// finished.
[[nodiscard]] inline WrittenText write_pipeline(const PipelineGraph& graph) {
    return written_pipeline(graph, WritingFor::Compiling);
}

// The text of a pipeline's pipeline.cpp to keep, also for a graph that isn't finished, or why the
// graph can't be written. A connection of a state value has no text yet, so it isn't kept.
[[nodiscard]] inline WrittenText write_pipeline_to_keep(const PipelineGraph& graph) {
    PipelineGraph without_state_values = graph;
    std::erase_if(without_state_values.connections, [&graph](const GraphConnection& connection) {
        const PortDescription* output_port = graph.find_port(
            connection.output.processor, connection.output.port, PortDirection::Output);
        return output_port != nullptr && output_port->kind == PortKind::State;
    });
    return written_pipeline(without_state_values, WritingFor::Keeping);
}

// The processor that each line of a written pipeline.cpp is about, by the line's number less one:
// the line that declares it and the line that calls it. Empty for every other line. An error
// that a compiler finds on such a line is that processor's.
[[nodiscard]] inline std::vector<std::string> processors_of_lines(std::string_view pipeline_text,
                                                                  const PipelineGraph& graph) {
    std::vector<std::string> processor_names;
    std::size_t line_start = 0;
    while (line_start < pipeline_text.size()) {
        std::size_t line_end = pipeline_text.find('\n', line_start);
        if (line_end == std::string_view::npos) {
            line_end = pipeline_text.size();
        }
        const std::string_view line = pipeline_text.substr(line_start, line_end - line_start);
        const std::size_t first_character = line.find_first_not_of(' ');
        const std::string_view without_indentation = first_character == std::string_view::npos
                                                         ? std::string_view()
                                                         : line.substr(first_character);
        const auto processor = std::ranges::find_if(
            graph.processors, [line, without_indentation](const GraphProcessor& candidate) {
                return line.ends_with(declaration_end_of(candidate.name)) ||
                       without_indentation.starts_with(call_start_of(candidate.name));
            });
        processor_names.emplace_back(processor == graph.processors.end() ? std::string()
                                                                         : processor->name);
        line_start = line_end + 1;
    }
    return processor_names;
}
